#!/usr/bin/env python3
"""Generate the object-schema reference page from the canonical OpenAPI spec.

`fumadocs-openapi` renders each operation's request/response schema inline, but
gives no single page that lists every object's fields — which is what the old
in-dashboard reference offered. This regenerates that page into the API section
so docs.wire.mn is the only place the API surface is documented.

Source of truth is api/openapi.yaml; the output is generated. Never hand-edit
content/docs/api/schemas.mdx — edit the spec and re-run `make docs-spec`.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

try:
    import yaml
except ImportError:  # pragma: no cover - dev machine setup issue
    sys.exit("PyYAML is required: pip install pyyaml")

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[2]
# Reads the vendored copy that sync-openapi.mjs just wrote, so this script sees
# exactly the spec the rest of the site was generated from.
SPEC = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parent / "openapi" / "wire.yaml"
OUT = HERE.parent / "content" / "docs" / "api" / "schemas.mdx"


def ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def resolve(spec: dict, ref: str) -> dict:
    node: object = spec
    for part in ref.lstrip("#/").split("/"):
        if not isinstance(node, dict):
            return {}
        node = node.get(part, {})
    return node if isinstance(node, dict) else {}


def type_label(spec: dict, s: dict) -> str:
    """Compact human-readable type, mirroring the old dashboard renderer."""
    if "$ref" in s:
        return ref_name(s["$ref"])
    # json.dumps renders literals the way the wire format shows them:
    # "succeeded", true, null — not Python's True/None.
    if s.get("enum"):
        return " | ".join(json.dumps(e, ensure_ascii=False) for e in s["enum"])
    if "const" in s:
        return json.dumps(s["const"], ensure_ascii=False)
    # OpenAPI 3.1 allows a type union, e.g. ["string", "null"] for nullable.
    raw = s.get("type", "object")
    names = [str(t) for t in raw] if isinstance(raw, list) else [str(raw)]
    if "array" in names:
        items = s.get("items")
        inner = type_label(spec, items) if items else "any"
        names = [f"{inner}[]" if n == "array" else n for n in names]
    return " | ".join(names)


def collect_fields(spec: dict, schema: dict) -> list[dict]:
    """Flatten an object schema (including allOf composition) into fields."""
    parts = [
        resolve(spec, p["$ref"]) if "$ref" in p else p
        for p in schema.get("allOf", [schema])
    ]
    fields: list[dict] = []
    for part in parts:
        required = set(part.get("required") or [])
        for name, fs in (part.get("properties") or {}).items():
            fields.append(
                {
                    "name": name,
                    "type": type_label(spec, fs),
                    "required": name in required,
                    "description": (fs.get("description") or "").strip(),
                }
            )
    return fields


def cell(text: str) -> str:
    """Escape a value for a Markdown table cell."""
    return text.replace("|", "\\|").replace("\n", " ").strip()


def main() -> None:
    if not SPEC.exists():
        sys.exit(f"OpenAPI source not found: {SPEC}")
    spec = yaml.safe_load(SPEC.read_text(encoding="utf-8"))
    schemas = (spec.get("components") or {}).get("schemas") or {}

    blocks: list[str] = []
    documented = 0
    for name, schema in schemas.items():
        fields = collect_fields(spec, schema)
        if not fields:
            continue
        documented += 1
        rows = "\n".join(
            "| `{name}` | `{type}` | {req} | {desc} |".format(
                name=cell(f["name"]),
                type=cell(f["type"]),
                req="✓" if f["required"] else "",
                desc=cell(f["description"]),
            )
            for f in fields
        )
        desc = (schema.get("description") or "").strip()
        intro = f"{desc}\n\n" if desc else ""
        blocks.append(
            f"## {name}\n\n{intro}| Талбар | Төрөл | Заавал | Тайлбар |\n"
            f"| --- | --- | --- | --- |\n{rows}"
        )

    body = "\n\n".join(blocks)
    page = f"""---
title: Object schemas
description: Wire API-ийн бүх объектын талбарын бүтэц — нэг хуудсанд.
---

{{/* This file is generated by scripts/generate-schemas.py. Do not edit directly. */}}

API-ийн буцаадаг болон хүлээж авдаг бүх объектын талбарын бүтэц — нийт
{documented} объект. **Заавал** баганын ✓ нь тухайн талбар заавал байхыг заана.
Хүсэлт, хариу бүрийн бодит жишээг [API reference](/docs/api)-ийн endpoint
хуудсаас үз.

{body}
"""

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(page, encoding="utf-8")
    print(f"generated object schemas ({documented}) -> {OUT.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()

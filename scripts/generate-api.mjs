// Generates the API reference MDX from the vendored OpenAPI spec into
// content/docs/api/. Committed output keeps the build hermetic (no network,
// no extra build step needed in Docker). Re-run via `pnpm sync-openapi`.
import { generateFiles } from "fumadocs-openapi";
import { createOpenAPI } from "fumadocs-openapi/server";
import { existsSync } from "node:fs";
import { join } from "node:path";

const specPath = join(import.meta.dirname, "../openapi/wire.yaml");
if (!existsSync(specPath)) {
  console.error(
    `Vendored OpenAPI spec missing: ${specPath}\nRun \`pnpm sync-openapi\` first.`,
  );
  process.exit(1);
}

const openapi = createOpenAPI({ input: ["./openapi/wire.yaml"] });

const OUTPUT_DIR = "content/docs/api";

// Build the index `<Cards>` ourselves: the built-in `index` helper skips
// grouped entries, so it renders empty when `groupBy: "tag"` is used.
function buildIndex(generatedEntries) {
  const cards = [];
  const escape = (s) => String(s).replace(/"/g, "&quot;");
  const toUrl = (filePath) =>
    "/docs/api/" +
    filePath
      .replace(/^content\/docs\/api\//, "")
      .replace(/\/index\.mdx$/, "")
      .replace(/\.mdx$/, "");

  const walk = (entry) => {
    if (entry.type === "group") {
      for (const child of entry.entries) walk(child);
      return;
    }
    const desc = entry.info.description
      ? ` description="${escape(entry.info.description)}"`
      : "";
    cards.push(
      `  <Card href="${toUrl(entry.path)}" title="${escape(entry.info.title)}"${desc} />`,
    );
  };

  for (const entries of Object.values(generatedEntries))
    for (const entry of entries) walk(entry);

  // The object-schema page (generate-schemas.py) is not an operation, so it is
  // never in generatedEntries — link it explicitly or it is unreachable.
  cards.push(
    `  <Card href="/docs/api/schemas" title="Object schemas" description="Every object's fields, types and required flags on one page." />`,
  );

  return `---
title: API Reference
description: Wire Merchant API — REST reference generated from the public OpenAPI spec.
---

{/* This file is generated by scripts/generate-api.mjs. Do not edit directly. */}

<Cards>
${cards.join("\n")}
</Cards>
`;
}

await generateFiles({
  input: openapi,
  output: OUTPUT_DIR,
  // One MDX page per operation, grouped into folders by tag.
  per: "operation",
  groupBy: "tag",
  beforeWrite(files) {
    files.push({
      path: "index.mdx",
      content: buildIndex(this.generatedEntries),
    });
  },
});

console.log("generated API reference -> content/docs/api");
